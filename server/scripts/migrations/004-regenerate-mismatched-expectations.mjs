#!/usr/bin/env node
/**
 * 004 — Regenerate stored expectations that the official solution disagrees with.
 *
 *     npm -w dwcode-server run migrate:expectations -- --dry-run                 # read-only report
 *     npm -w dwcode-server run migrate:expectations -- --dry-run --show <slug>   # full diff for one
 *     npm -w dwcode-server run migrate:expectations -- --slugs a,b,c             # writes ONLY those
 *
 * `audit:problems` reports problems whose official solution does not produce a
 * stored expectation. Users submitting a correct answer fail those problems.
 * Each mismatch is classified, because they need different fixes:
 *
 *  - SOLUTION_ERROR: the solution fails to compile or throws on some case.
 *    The solution is broken; regenerating from it is impossible. Fix by hand
 *    (like migration 003), never here.
 *  - SHAPE_ONLY: same value, different text (key order, whitespace, 1 vs 1.0,
 *    quoting). Regenerating is safe: the meaning is unchanged.
 *  - VALUE_DIFF: the solution computes something else. Either the expectation
 *    or the solution is wrong. Regenerate ONLY after a human has read the
 *    problem statement and agrees the solution is right.
 *
 * SAFETY
 *  - Never writes without `--slugs`; there is no "fix everything" mode.
 *  - A slug is written only if its solution compiles and runs on EVERY case.
 *  - Expectations are generated by the real compiler, never by hand (CLAUDE.md).
 *  - Before writing, the problem's previous examples/testCases/hiddenTestCases
 *    are copied to `problems_expectations_backup` (one doc per problem per run).
 *  - The update is conditional on the document being unchanged since it was read.
 *  - Idempotent: a re-run finds nothing to change for fixed problems.
 *  - Additive: no schema change, no deploy ordering.
 */
import mongoose from "mongoose";
import { COMPILER_URL, casesOf, checkCases } from "../lib/compiler.mjs";

const DRY_RUN = process.argv.includes("--dry-run");
const argValue = (name) => {
  const i = process.argv.indexOf(name);
  return i > -1 ? process.argv[i + 1] : null;
};
const WRITE_SLUGS = new Set((argValue("--slugs") ?? "").split(",").map((s) => s.trim()).filter(Boolean));
const SHOW = argValue("--show");

/** Parse as JSON and re-serialise with sorted keys; null when not JSON. */
function canonical(text) {
  const sortKeys = (v) =>
    Array.isArray(v)
      ? v.map(sortKeys)
      : v && typeof v === "object"
        ? Object.fromEntries(Object.keys(v).sort().map((k) => [k, sortKeys(v[k])]))
        : v;
  try {
    return JSON.stringify(sortKeys(JSON.parse(String(text).trim())));
  } catch {
    return null;
  }
}

function classify(failures) {
  if (failures.some((f) => f.actual.startsWith("<compiler error"))) return "SOLUTION_ERROR";
  const sameValue = failures.every((f) => {
    const a = canonical(f.actual);
    const e = canonical(f.expected);
    return a !== null && a === e
      ? true
      : String(f.actual).replace(/\s+/g, "") === String(f.expected).replace(/\s+/g, "");
  });
  return sameValue ? "SHAPE_ONLY" : "VALUE_DIFF";
}

const short = (s, n = 160) => {
  const one = String(s ?? "").replace(/\s+/g, " ");
  return one.length > n ? `${one.slice(0, n)}…` : one;
};

/** New arrays with each failing case's expectation replaced by the solution's output. */
function regenerated(problem, results) {
  const byLabel = new Map(results.map((r) => [r.label, r]));
  const pick = (label, old) => {
    const r = byLabel.get(label);
    return r && !r.passed ? r.actual : old;
  };
  return {
    examples: (problem.examples ?? []).map((e, i) => ({ ...e, output: pick(`example ${i + 1}`, e.output) })),
    testCases: (problem.testCases ?? []).map((t, i) => ({ ...t, expectedOutput: pick(`test ${i + 1}`, t.expectedOutput) })),
    hiddenTestCases: (problem.hiddenTestCases ?? []).map((t, i) => ({
      ...t,
      expectedOutput: pick(`hidden ${i + 1}`, t.expectedOutput),
    })),
  };
}

async function main() {
  if (!process.env.MONGODB_URI) throw new Error("MONGODB_URI is not set (server/.env).");
  if (!DRY_RUN && WRITE_SLUGS.size === 0) {
    throw new Error("Refusing to write without --slugs a,b,c. Run with --dry-run first.");
  }
  const host = process.env.MONGODB_URI.replace(/\/\/[^@]*@/, "//<credentials>@").split("?")[0];
  console.log(`${DRY_RUN ? "DRY RUN" : "LIVE RUN"} against ${host}\nCompiler: ${COMPILER_URL}\n`);

  await mongoose.connect(process.env.MONGODB_URI, { autoIndex: false });
  const db = mongoose.connection.db;
  const problems = await db.collection("problems").find({ solution: { $type: "string", $ne: "" } }).sort({ slug: 1 }).toArray();

  const buckets = { SOLUTION_ERROR: [], SHAPE_ONLY: [], VALUE_DIFF: [] };
  let written = 0;

  for (const problem of problems) {
    const results = await checkCases(problem.solution, casesOf(problem));
    const failures = results.filter((r) => !r.passed);
    if (failures.length === 0) continue;

    const kind = classify(failures);
    buckets[kind].push(problem.slug);
    const total = results.length;
    const kinds = [...new Set(failures.map((f) => f.kind))].join("/");
    console.log(`${kind.padEnd(15)} ${problem.slug}  (${failures.length}/${total} cases: ${kinds}, ${problem.difficulty ?? "?"})`);

    const detail = SHOW === problem.slug ? failures : failures.slice(0, 1);
    for (const f of detail) {
      const width = SHOW === problem.slug ? 4000 : 160;
      console.log(`    ${f.label}\n      expected ${short(f.expected, width)}\n      solution ${short(f.actual, width)}`);
    }
    if (SHOW === problem.slug) console.log(`\n    statement: ${short(problem.description, 4000)}\n\n    solution:\n${problem.solution}\n`);

    if (!WRITE_SLUGS.has(problem.slug)) continue;
    if (kind === "SOLUTION_ERROR") {
      console.log("    SKIP: solution does not run on every case — fix the solution first.");
      continue;
    }
    if (DRY_RUN) {
      console.log(`    would regenerate ${failures.length} expectation(s)`);
      continue;
    }
    const next = regenerated(problem, results);
    await db.collection("problems_expectations_backup").insertOne({
      problemId: problem._id,
      slug: problem.slug,
      migration: "004",
      backedUpAt: new Date(),
      examples: problem.examples ?? [],
      testCases: problem.testCases ?? [],
      hiddenTestCases: problem.hiddenTestCases ?? [],
    });
    const res = await db.collection("problems").updateOne(
      { _id: problem._id, updatedAt: problem.updatedAt, solution: problem.solution },
      { $set: next },
    );
    if (res.modifiedCount === 1) {
      written++;
      console.log(`    regenerated ${failures.length} expectation(s); old values in problems_expectations_backup`);
    } else {
      console.log("    NOT written: document changed since it was read — re-run.");
    }
  }

  const unknown = [...WRITE_SLUGS].filter((s) => !Object.values(buckets).flat().includes(s));
  console.log(`\n${problems.length} problems with a solution checked.`);
  for (const [kind, slugs] of Object.entries(buckets)) console.log(`  ${kind.padEnd(15)} ${slugs.length}`);
  if (unknown.length) console.log(`\n--slugs not mismatched (ignored): ${unknown.join(", ")}`);
  if (!DRY_RUN) console.log(`\nWrote ${written} problem(s).`);
}

main()
  .catch((err) => {
    console.error(`\nAborted: ${err.message}`);
    process.exitCode = 1;
  })
  .finally(() => mongoose.disconnect());
